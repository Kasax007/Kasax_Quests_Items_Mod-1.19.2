def join(glyphs, gap=1):
    """Glyphs side by side (same height), 'gap' empty columns between them."""
    h = max(len(g) for g in glyphs)
    rows = []
    for y in range(h):
        parts = []
        for g in glyphs:
            pad = (h - len(g))
            r = g[y - pad] if y >= pad else '.' * len(g[0])
            parts.append(r)
        rows.append(('.' * gap).join(parts))
    return rows


def roman(n, max_width=12):
    numerals = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X']
    s = numerals[n]
    rows = join([ROMAN[c] for c in s])
    if len(rows[0]) > max_width:
        rows = join([ROMAN['i' if c == 'I' else c] for c in s])
    return rows


def number(n):
    if n < 10:
        return BOLD[str(n)]
    return join([NARROW[c] for c in str(n)])
