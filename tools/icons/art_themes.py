for q in range(5):
    c = Canvas()
    for y in range(5, 11):
        for x in range(1, 15):
            c.set(x, y, 'dark', 'b')
    filled = round(12 * q / 4)
    for y in range(6, 10):
        for x in range(2, 2 + filled):
            c.set(x, y, 'lime', 'v')
    add('progress_bar_%d' % (q * 25), 'Progress %d%% Icon' % (q * 25), 'progress', c, keywords='progress bar percent loading')

for q in range(1, 5):
    c = Canvas()
    m = mask_circle()
    for (x, y) in m:
        import math
        ang = (math.degrees(math.atan2(x + 0.5 - 8, -(y + 0.5 - 8))) + 360) % 360
        c.set(x, y, 'lime' if ang < q * 90 - 0.01 else 'grey', 'b' if ang < q * 90 - 0.01 else 'f')
    add('progress_pie_%d' % q, 'Progress %d of 4 Icon' % q, 'progress', c, keywords='pie quarter part stage')

