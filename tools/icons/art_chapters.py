def battery(level):
    c = Canvas()
    for x in range(6, 10):
        for y in range(1, 3):
            c.set(x, y, 'iron')
    for y in range(3, 15):
        for x in range(4, 12):
            c.set(x, y, 'grey')
    for y in range(4, 14):
        for x in range(5, 11):
            c.set(x, y, 'dark', 'f')
    col = {0: None, 1: 'red', 2: 'yellow', 3: 'lime'}[level]
    rows = {0: 0, 1: 3, 2: 6, 3: 10}[level]
    for y in range(14 - rows, 14):
        for x in range(5, 11):
            c.set(x, y, col, 'b')
    return c


