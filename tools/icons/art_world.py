def coin(mat, mark):
    c = Canvas()
    fill(c, mask_circle(12, 2, 2), mat, 's')
    fill(c, {(x, y) for (x, y) in mask_circle(8, 4, 4)}, mat + '2', 'b')
    center_stamp(c, mark, mat, '1', box=(4, 4, 8, 8))
    return c


