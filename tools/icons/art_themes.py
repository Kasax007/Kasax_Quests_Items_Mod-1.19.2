def chevrons(n, mat='gold'):
    c = Canvas()
    one = parse("""
......yyyy......
....yyyyyyyy....
..yyyyy..yyyyy..
.yyyy......yyyy.""")
    top = 1 + (3 - n) * 5 // 2 + 1
    for k in range(n):
        m = mat if k % 2 == 0 else mat + '2'
        for y, r in enumerate(one):
            for x, ch in enumerate(r):
                if ch == 'y':
                    c.set(x, top + k * 5 + y, m)
    return c


